"""The flag registry: every ``ZOE_*`` environment flag declares itself here, once.

One entry per flag: ``name``, ``type`` (``bool``/``int``/``float``/``str``/``list``), ``default``,
``allowed`` values (a mode flag such as ``off|shadow|enforce`` lists them), ``owner_doc`` (the doc that
explains the flag) and, where the readers legitimately disagree on a default, an acknowledgement
(``divergent_ok``: ``{file: reason}``).

Why (deep dive 2026-10-18, B6): 673 flags, 647 raw ``os.getenv`` reads against 164 ``typed_env`` calls,
and a flag read with different defaults in different places. The failure this ends is a flag whose
meaning lives in N call sites instead of in one declaration.

How it is used
--------------
- **Reading** — new code reads a flag with ``typed_env.flag("ZOE_X")``: the type, default and allowed
  values come from this file, the canonical bool rule (``1/true/yes/on`` vs ``0/false/no/off``) is
  applied, and nothing is hard-coded at the call site. Existing ``env_bool("ZOE_X", False)`` /
  ``os.environ.get(...)`` call sites keep working; migrate them as their files are touched.
- **Declaring** — add the flag with ``python3 tools/audit/flag_inventory.py --sync-registry`` (it infers a
  starting spec from the read sites; correct the type/default/allowed/doc by hand, in place).
- **Enforcement** — ``tests/unit/test_flag_registry.py`` (``ci_safe``) fails on any ``ZOE_*`` read of an
  unregistered name, on a reader whose hard-coded default differs from the declared one (unless
  acknowledged here), and on a new direct (non-``typed_env``) read beyond the per-file ratchet in
  ``docs/knowledge/flag-ratchet.json``. ``docs/knowledge/flag-inventory.{md,json}`` is GENERATED from
  this registry joined with the scanner's facts.

Pure data + stdlib only: the inventory tool imports this file by path, and ``typed_env`` imports it lazily.

The default recorded for a flag is the one in force when nothing sets it. Where the live ``.env`` or a
unit pins a different value, that is recorded in ``note`` — the registry never changes live behaviour.
"""
from __future__ import annotations

from dataclasses import dataclass, field

FLAG_TYPES = ("bool", "int", "float", "str", "list")


@dataclass(frozen=True)
class FlagSpec:
    name: str
    type: str
    default: object
    allowed: tuple[str, ...] | None = None
    owner_doc: str = ""
    note: str = ""
    divergent_ok: dict = field(default_factory=dict)

    def as_dict(self) -> dict:
        return {
            "type": self.type,
            "default": self.default,
            "allowed": list(self.allowed) if self.allowed else None,
            "owner_doc": self.owner_doc,
            "note": self.note,
            "divergent_ok": dict(self.divergent_ok),
        }


FLAGS: dict[str, FlagSpec] = {}


def _f(name: str, type_: str, default: object, *, allowed: tuple[str, ...] | None = None, doc: str = "",
       note: str = "", divergent_ok: dict | None = None) -> FlagSpec:
    if name in FLAGS:
        raise ValueError(f"flag registered twice: {name}")
    if type_ not in FLAG_TYPES:
        raise ValueError(f"{name}: unknown flag type {type_!r} (expected one of {FLAG_TYPES})")
    spec = FlagSpec(name, type_, default, tuple(allowed) if allowed else None, doc, note, dict(divergent_ok or {}))
    FLAGS[name] = spec
    return spec


def spec(name: str) -> FlagSpec:
    """The declared spec for ``name``; an unregistered flag is a bug, not a default."""
    try:
        return FLAGS[name]
    except KeyError:
        raise KeyError(
            f"{name} is not in the flag registry (services/zoe-data/flag_registry.py) - "
            "run: python3 tools/audit/flag_inventory.py --sync-registry"
        ) from None


def is_registered(name: str) -> bool:
    return name in FLAGS


