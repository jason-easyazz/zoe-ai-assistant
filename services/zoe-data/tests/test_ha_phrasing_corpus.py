# ── corpus integrity ────────────────────────────────────────────────────────


def test_every_label_is_mapped_and_every_mapping_is_used(rows, mapping):
    corpus_labels = {r["label"] for r in rows} | set((mapping.get("relabel") or {}).values())
    mapped = set(mapping["labels"])
    assert corpus_labels - mapped == set(), "corpus labels with no mapping entry"
    assert mapped - corpus_labels == set(), "mapping entries no sentence uses (stale)"
    texts = {r["text"] for r in rows}
    assert set(mapping.get("relabel") or {}) <= texts, "relabel keys must be corpus sentences, verbatim"
    for label, spec in mapping["labels"].items():
        assert set(spec) <= {"accept", "forbid", "check_seconds", "unsupported"}, label
        if spec.get("unsupported"):
            assert not spec.get("accept"), f"{label}: an unsupported label accepts nothing"
        overlap = [g for g in spec.get("forbid") or [] if g in (spec.get("accept") or [])]
        assert not overlap, f"{label}: a glob cannot be both accepted and forbidden: {overlap}"


def test_corpus_matches_its_recorded_sources(rows):
    sources = json.loads(SOURCES.read_text(encoding="utf-8"))
    counts = Counter(r["src"] for r in rows)
    assert dict(counts) == {k: v for k, v in sources["counts"].items() if k != "total" and v}
    assert len(rows) == sources["counts"]["total"]
    for row in rows:
        assert set(row) <= {"src", "label", "text", "seconds"}, row
        assert row["text"] == row["text"].strip() and row["text"], row
    attribution = ATTRIBUTION.read_text(encoding="utf-8")
    for pin in sources["pins"].values():
        assert re.fullmatch(r"[0-9a-f]{40}", pin["commit"]), pin
        # The credit must name the exact upstream commit the data came from.
        assert pin["commit"] in attribution and pin["repo"] in attribution, pin
    assert (FIXTURES / "LICENSE-Apache-2.0.txt").is_file(), "Apache-2.0 requires the licence text to travel with OVOS-derived data"


def test_corpus_is_free_of_duplicates_within_a_source(rows):
    seen = Counter((r["src"], r["label"], r["text"].lower()) for r in rows)
    dupes = [k for k, v in seen.items() if v > 1 and k[0] != "ha_test"]  # HA's own test set repeats a few strings
    assert dupes == []


# ── the ratchet ─────────────────────────────────────────────────────────────


def test_phrasing_corpus_ratchet(zoe_score):
    current = as_baseline(zoe_score)
    print("\n" + report(zoe_score))
    if os.environ.get("ZOE_HA_CORPUS_REBASELINE") == "1":
        BASELINE.write_text(dump_baseline(current), encoding="utf-8")
        pytest.skip(f"baseline rewritten: {BASELINE}")
    baseline = json.loads(BASELINE.read_text(encoding="utf-8"))
    regress, improve = ratchet_problems(current, baseline)
    if regress:
        detail = []
        for line in regress:
            label = line.split(":", 1)[0]
            for metric in ("wrong_write", "forbidden", "wrong"):
                for ex in zoe_score.examples.get((label, metric), [])[:3]:
                    detail.append(f"    {label} {metric}: {ex}")
        pytest.fail("phrasing corpus REGRESSED:\n  " + "\n  ".join(regress) + "\n" + "\n".join(detail))
    if improve:
        pytest.fail(
            "phrasing corpus IMPROVED - lock it in: re-run with ZOE_HA_CORPUS_REBASELINE=1 and commit "
            "fixtures/ha_intents/baseline.json in this PR:\n  " + "\n  ".join(improve)
        )


def test_ratchet_catches_a_planted_false_write(rows, mapping, zoe_score):
    """Negative control: a matcher that starts a timer for every timer-ish sentence must trip the gate."""

    def greedy(text: str) -> Claim | None:
        if "timer" in text.lower():
            return Claim("sky:timer/create", 300)
        return zoe_claim(text)

    with _quiet_logs():
        planted = as_baseline(score(rows, mapping, greedy))
    honest = as_baseline(zoe_score)
    regress, _ = ratchet_problems(planted, honest)
    assert any("wrong_write" in r for r in regress), regress
    assert planted["labels"]["HassTimerStatus"]["wrong_write"] > honest["labels"]["HassTimerStatus"]["wrong_write"]


def test_timer_length_is_part_of_correctness(mapping):
    """A timer with the wrong length is a wrong WRITE, not a correct claim."""
    rows = [{"src": "t", "label": "HassStartTimer", "text": "set a timer for half an hour", "seconds": 1800}]
    s = score(rows, mapping, lambda _t: Claim("sky:timer/create", 3600))
    assert s.labels["HassStartTimer"]["wrong_write"] == 1
    s = score(rows, mapping, lambda _t: Claim("sky:timer/create", 1800))
    assert s.labels["HassStartTimer"]["correct"] == 1
