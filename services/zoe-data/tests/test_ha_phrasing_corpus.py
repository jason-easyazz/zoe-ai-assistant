"""Phrasing regression corpus: Home Assistant + OVOS sentences through Zoe's fast path.

What it measures (research record docs/research/common-questions-ha-intents-2026-10.md,
section 6): every sentence in ``fixtures/ha_intents/en.jsonl`` (HA's labelled English
test sentences, hassil samples of HA's templates, and the OVOS weather skill's
templates; regenerated by ``scripts/maintenance/ha_intents_corpus.py``) is run through
Zoe's two deterministic matchers in cascade order - ``classify_skybridge_intent`` first,
``intent_router.detect_intent`` only when Skybridge claimed nothing - and scored
against ``fixtures/ha_intents/mapping.yaml``:

* correct      the claim is one the label accepts (and a timer carries the right length)
* wrong        any other claim (the turn never reaches the smarter tiers)
* wrong_write  a wrong claim that writes or actuates - THE gate
* forbidden    a wrong claim the mapping names as a known hazard for that label
* miss         no claim; the turn falls through to the router head / brain

It RATCHETS against ``fixtures/ha_intents/baseline.json``, per label and in total:
``correct`` may only go up, ``wrong``/``wrong_write``/``forbidden`` may only go down.
A change that IMPROVES a number must re-baseline in the same PR (otherwise the gain is
not locked in and could silently regress later):

    ZOE_HA_CORPUS_REBASELINE=1 python -m pytest services/zoe-data/tests/test_ha_phrasing_corpus.py

Pure regex: no model, no network, no DB, no clock-dependent output.
"""

from __future__ import annotations

import fnmatch
import json
import logging
import os
import re
from collections import Counter
from contextlib import contextmanager
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable

import pytest
import yaml

pytestmark = pytest.mark.ci_safe  # pure regex over committed data

import intent_router
import skybridge_service

FIXTURES = Path(__file__).parent / "fixtures" / "ha_intents"
CORPUS = FIXTURES / "en.jsonl"
MAPPING = FIXTURES / "mapping.yaml"
BASELINE = FIXTURES / "baseline.json"
SOURCES = FIXTURES / "sources.json"
ATTRIBUTION = FIXTURES / "ATTRIBUTION.md"
METRICS = ("n", "correct", "wrong", "wrong_write", "forbidden", "miss")
UP_ONLY = ("correct",)
DOWN_ONLY = ("wrong", "wrong_write", "forbidden")


@dataclass(frozen=True)
class Claim:
    tag: str
    seconds: int | None = None  # a timer claim's length


@dataclass
class Score:
    labels: dict[str, Counter] = field(default_factory=dict)
    examples: dict[tuple[str, str], list[str]] = field(default_factory=dict)

    def bump(self, label: str, metric: str, text: str | None = None) -> None:
        self.labels.setdefault(label, Counter())[metric] += 1
        if text is not None:
            bucket = self.examples.setdefault((label, metric), [])
            if len(bucket) < 5:
                bucket.append(text)

    def totals(self) -> Counter:
        out: Counter = Counter()
        for c in self.labels.values():
            out.update(c)
        return out


def zoe_claim(text: str) -> Claim | None:
    """Zoe's deterministic claim for ``text``, in voice-cascade order."""
    sky = skybridge_service.classify_skybridge_intent(text)
    if sky is not None:
        secs = int(sky.duration_seconds) if sky.domain == "timer" and sky.action == "create" else None
        return Claim(f"sky:{sky.domain}/{sky.action}", secs)
    intent = intent_router.detect_intent(text, log_miss=False)
    if intent is None:
        return None
    sub = intent.slots.get("action") or intent.slots.get("command")
    tag = f"ir:{intent.name}" + (f"/{sub}" if isinstance(sub, str) and sub else "")
    secs = None
    if intent.name == "timer_create":
        try:
            secs = int(round(float(intent.slots.get("minutes")) * 60))
        except (TypeError, ValueError):
            secs = None
    return Claim(tag, secs)


def _matches(tag: str, globs: list[str]) -> bool:
    return any(fnmatch.fnmatchcase(tag, g) for g in globs)


def load_rows() -> list[dict]:
    return [json.loads(line) for line in CORPUS.read_text(encoding="utf-8").splitlines() if line.strip()]


def load_mapping() -> dict:
    return yaml.safe_load(MAPPING.read_text(encoding="utf-8"))


def score(rows: list[dict], mapping: dict, claim_fn: Callable[[str], Claim | None] = zoe_claim) -> Score:
    writes = mapping["writes"]
    relabel = mapping.get("relabel") or {}
    out = Score()
    for row in rows:
        text = row["text"]
        label = relabel.get(text, row["label"])
        spec = mapping["labels"][label]
        out.bump(label, "n")
        claim = claim_fn(text)
        if claim is None:
            out.bump(label, "miss")
            continue
        ok = _matches(claim.tag, spec.get("accept") or [])
        if ok and spec.get("check_seconds") and row.get("seconds") is not None:
            ok = claim.seconds == row["seconds"]
        if ok:
            out.bump(label, "correct")
            continue
        shown = f"{text!r} -> {claim.tag}" + (f" ({claim.seconds}s)" if claim.seconds is not None else "")
        out.bump(label, "wrong", shown)
        if _matches(claim.tag, writes):
            out.bump(label, "wrong_write", shown)
        if _matches(claim.tag, spec.get("forbid") or []):
            out.bump(label, "forbidden", shown)
    return out


def as_baseline(s: Score) -> dict:
    def pick(c: Counter) -> dict:
        return {m: int(c.get(m, 0)) for m in METRICS}

    return {"total": pick(s.totals()), "labels": {k: pick(v) for k, v in sorted(s.labels.items())}}


def dump_baseline(b: dict) -> str:
    """One line per label, so a baseline diff reads label by label."""
    rows = [f"    {json.dumps(k)}: {json.dumps(v, sort_keys=True)}" for k, v in sorted(b["labels"].items())]
    return ('{\n  "total": ' + json.dumps(b["total"], sort_keys=True) + ',\n  "labels": {\n'
            + ",\n".join(rows) + "\n  }\n}\n")


def ratchet_problems(current: dict, baseline: dict) -> tuple[list[str], list[str]]:
    """(regressions, improvements) of ``current`` against ``baseline``."""
    regress: list[str] = []
    improve: list[str] = []
    scopes = [("TOTAL", current["total"], baseline["total"])]
    for label in sorted(set(current["labels"]) | set(baseline["labels"])):
        scopes.append((label, current["labels"].get(label), baseline["labels"].get(label)))
    for name, cur, base in scopes:
        if cur is None or base is None or cur["n"] != base["n"]:
            regress.append(f"{name}: sentence set changed (now {cur and cur['n']}, baseline {base and base['n']})"
                           " - regenerate + re-baseline together")
            continue
        for m in UP_ONLY:
            if cur[m] < base[m]:
                regress.append(f"{name}: {m} {base[m]} -> {cur[m]}")
            elif cur[m] > base[m]:
                improve.append(f"{name}: {m} {base[m]} -> {cur[m]}")
        for m in DOWN_ONLY:
            if cur[m] > base[m]:
                regress.append(f"{name}: {m} {base[m]} -> {cur[m]}")
            elif cur[m] < base[m]:
                improve.append(f"{name}: {m} {base[m]} -> {cur[m]}")
    return regress, improve


def report(s: Score) -> str:
    t = s.totals()
    n = max(1, t["n"])
    lines = [
        f"HA/OVOS phrasing corpus: {t['n']} sentences | correct {t['correct']} ({100 * t['correct'] / n:.1f}%)"
        f" | wrong {t['wrong']} ({100 * t['wrong'] / n:.1f}%) | wrong_write {t['wrong_write']}"
        f" | forbidden {t['forbidden']} | miss {t['miss']}",
        f"{'label':38} {'n':>5} {'ok':>5} {'wrong':>5} {'w_wr':>5} {'forb':>5} {'miss':>5}",
    ]
    for label, c in sorted(s.labels.items()):
        lines.append(f"{label:38} {c['n']:5d} {c['correct']:5d} {c['wrong']:5d} {c['wrong_write']:5d}"
                     f" {c['forbidden']:5d} {c['miss']:5d}")
    return "\n".join(lines)


@contextmanager
def _quiet_logs():
    """The matchers log every miss / gate decision; 3k sentences of that is noise."""
    previous = logging.root.manager.disable
    logging.disable(logging.CRITICAL)
    try:
        yield
    finally:
        logging.disable(previous)


