#!/usr/bin/env python3
"""Generate docs/knowledge/live-state.json - the ZOE_* flag DEFAULTS as the code ships them.

This file is NOT the live state of the box, despite its name (the name is the roadmap's, deep-dive task C1). It is derived
from ``docs/knowledge/flag-inventory.json`` (itself extracted from the code by ``flag_inventory.py``), so it can only say what
a flag does when nobody sets it. What is actually ON in the running processes is read with
``scripts/maintenance/zoe_ground_truth.sh``; a roadmap that wants to say "this flag is ON live" says so in prose and marks the
date, and the CI check (``tests/unit/test_roadmap_flag_claims.py``) never pretends to verify it.

What it is for: ``docs/ROADMAP.md`` writes a claim about a code default as ``[default ZOE_NAME=value]``, and the test fails when
that claim contradicts this derivation. That is the check that would have caught "documented dark, actually shadow/enforce"
drift of the kind recorded in the 2026-10-18 deep dive, for the half of it code can see (the default).

Booleans vs numbers: a default of ``1`` / ``0`` is on / off to a flag read as a boolean but is just a number to one read as an
integer (``ZOE_SMART_TURN_THREADS=1`` is one thread). The inventory carries no type, so ``reader_kinds`` recovers it from the reader
shape at each call site (``env_bool`` vs ``env_int`` / ``int(os.environ.get(...))`` vs ``== "1"``), and a numeric default is turned
into on/off ONLY with positive evidence that the flag is read as a bool. Each flag records its ``kind``.

Deterministic by construction (sorted, no timestamps), so regeneration diffs show real flag changes only.

Usage:
    python3 tools/audit/live_state.py            # write docs/knowledge/live-state.json
    python3 tools/audit/live_state.py --check    # exit 1 when the committed file is stale (writes nothing)
"""
from __future__ import annotations

import argparse
import ast
import importlib.util
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
INVENTORY = "docs/knowledge/flag-inventory.json"
OUT = "docs/knowledge/live-state.json"

_ON = {"1", "true", "yes", "on", "enabled", "enable"}
_OFF = {"0", "false", "no", "off", "none", "disabled", "disable", "null"}

# The reader shapes that decide whether a numeric default means on/off or is just a number. Spellings mirror flag_inventory.py.
_INT_READERS = {"env_int", "_int_env", "_env_int", "_int_from_env"}
_FLOAT_READERS = {"env_float", "_float_env", "_env_float", "env_float_failsafe"}
_BOOL_READERS = {"env_bool", "_env_bool", "_env_flag", "_env_enabled"}
_STR_READERS = {"env_str", "env_list"}

NOTE = (
    "GENERATED by tools/audit/live_state.py from docs/knowledge/flag-inventory.json. These are the flag DEFAULTS as the code "
    "ships them, not the values set on the running box (read those with scripts/maintenance/zoe_ground_truth.sh). "
    "'unset' = no default argument or an empty-string default; it is compatible with a claim of 'off'. "
    "A default of 1 or 0 is written 'on' / 'off' ONLY for a flag the code reads as a boolean; on a flag read as a number, or whose "
    "reader shape is not recognised, it stays the literal 1 or 0. 'kind' says which: bool | number | str | unknown."
)


def _is_number_token(token: str) -> bool:
    try:
        float(token)
    except ValueError:
        return False
    return True


def normalise_default(raw: str, kind: str = "unknown") -> str:
    """One inventory default expression -> a comparable token: on | off | unset | dynamic | required | <lowercased literal>.

    ``kind`` is how the flag is READ (``flag_kind``): ``bool`` | ``number`` | ``str`` | ``unknown``. It resolves the one real
    ambiguity, a NUMERIC default: ``1`` / ``0`` are on / off to a boolean reader but are just the numbers 1 and 0 to
    ``int(os.environ.get(...))``. So a numeric default becomes on/off only when ``kind == "bool"``; a number-read or unrecognised flag
    keeps the literal. Words that cannot be numbers (``true``, ``no``, ``off`` ...) and Python ``True`` / ``False`` are unambiguous
    and normalise whatever ``kind`` is.
    """
    text = str(raw).strip()
    if text in ("-", ""):
        return "unset"
    if text == "dynamic":
        return "dynamic"
    if text == "(required)":
        return "required"
    try:
        value = ast.literal_eval(text)
    except (ValueError, SyntaxError):
        return text.lower()
    if value is None:
        return "unset"
    if isinstance(value, bool):
        return "on" if value else "off"
    token = str(value).strip().lower()
    if token == "":
        return "unset"
    if _is_number_token(token) and kind != "bool":
        return token
    if token in _ON:
        return "on"
    if token in _OFF:
        return "off"
    return token


def _load_flag_inventory():
    """flag_inventory.py is a sibling script, not a package: load it by path so this works however live_state itself was loaded."""
    spec = importlib.util.spec_from_file_location("_zoe_flag_inventory", Path(__file__).resolve().with_name("flag_inventory.py"))
    mod = importlib.util.module_from_spec(spec)
    sys.modules.setdefault("_zoe_flag_inventory", mod)
    spec.loader.exec_module(mod)
    return mod


def _helper_kind(name: str) -> str | None:
    if name in _INT_READERS or name in _FLOAT_READERS:
        return "number"
    if name in _BOOL_READERS:
        return "bool"
    if name in _STR_READERS:
        return "str"
    return None


_BOOL_VOCAB = _ON | _OFF | {""}


def _compare_kind(cmp: ast.Compare) -> set[str]:
    """A comparison is boolean evidence only when it is against the on/off vocabulary (``== "1"``, ``in ("1", "true")``,
    ``not in {"0", "false"}``, or a named set such as ``_TRUTHY``). A comparison against a mode word (``== "enforce"``) says the flag
    is a mode string, which proves nothing about a numeric default."""
    words: list[str] = []
    for comp in cmp.comparators:
        if isinstance(comp, ast.Name):
            if any(k in comp.id.lower() for k in ("true", "truthy", "falsy", "false", "_on", "yes", "enabled")):
                return {"bool"}
            return set()
        for node in ast.walk(comp):
            if isinstance(node, ast.Constant):
                if not isinstance(node.value, str):
                    return set()
                words.append(node.value.strip().lower())
    if words and all(w in _BOOL_VOCAB for w in words):
        return {"bool"}
    return {"str"} if words else set()


def _consumption(node: ast.AST, parents: dict, uses_of, depth: int = 0) -> set[str]:
    """How the value produced at ``node`` (an untyped env read) is consumed: a subset of {"number", "bool"}.

    ``int(read)`` / ``float(read)`` -> number. ``read == "1"``, ``read in (...)``, ``not read``, ``bool(read)`` -> bool. Method chains
    (``.strip().lower()``) and ``or`` / ``if-else`` fallbacks are looked through, and a read assigned to a plain name is followed to
    that name's uses in its scope (one hop of aliasing). A truthiness test (``if read:``) is NOT evidence: the string "0" is truthy.
    """
    cur = node
    while True:
        parent = parents.get(id(cur))
        if parent is None:
            return set()
        if isinstance(parent, ast.Call):
            if parent.func is cur:
                cur = parent  # read.strip().lower(): the read's method is being called, so the chain's result is what we follow
                continue
            fn = parent.func
            if cur in parent.args and isinstance(fn, ast.Name):
                name = fn.id.lstrip("_").lower()
                if name in ("int", "float"):
                    return {"number"}
                if name == "bool" or "truthy" in name or name in ("as_bool", "to_bool", "parse_bool", "env_truthy"):
                    return {"bool"}
            return set()
        if isinstance(parent, ast.Compare):
            return _compare_kind(parent)
        if isinstance(parent, ast.UnaryOp) and isinstance(parent.op, ast.Not):
            return {"bool"}
        if isinstance(parent, (ast.BoolOp, ast.IfExp, ast.Attribute)):
            cur = parent
            continue
        if isinstance(parent, (ast.Assign, ast.AnnAssign)) and depth == 0:
            targets = parent.targets if isinstance(parent, ast.Assign) else [parent.target]
            out: set[str] = set()
            for target in targets:
                if isinstance(target, ast.Name):
                    for use in uses_of(parent, target.id):
                        out |= _consumption(use, parents, uses_of, depth + 1)
            return out
        return set()


def reader_kinds(repo: Path, inventory: dict) -> dict[str, set[str]]:
    """flag -> the set of ways the code reads it: ``bool`` | ``number`` | ``str``, from the reader shape at each call site.

    Typed helpers decide outright (``env_bool`` -> bool, ``env_int`` / ``env_float`` -> number, ``env_str`` -> str); a bare
    module-local delegator to one inherits its kind; any other ``os.environ.get`` / ``getenv`` read is classified by how its value is
    consumed (``_consumption``). Only the production reader files the inventory lists are parsed. A flag no read could be classified
    for is simply absent, which ``flag_kind`` calls "unknown".
    """
    fi = _load_flag_inventory()
    prod = inventory.get("flags", {}).get("prod", {})
    files = sorted({r for rec in prod.values() for r in rec.get("readers", [])})
    kinds: dict[str, set[str]] = {}
    for rel in files:
        try:
            tree = ast.parse((repo / rel).read_text(encoding="utf-8"))
        except (OSError, SyntaxError, UnicodeDecodeError):
            continue
        parents = {id(ch): node for node in ast.walk(tree) for ch in ast.iter_child_nodes(node)}
        delegators = fi._typed_delegators(tree)
        delegated: dict[str, str] = {}
        for fn in ast.iter_child_nodes(tree):
            if isinstance(fn, ast.FunctionDef) and fn.name in delegators:
                body = [s for s in fn.body if not (isinstance(s, ast.Expr) and isinstance(s.value, ast.Constant))]
                inner = _helper_kind(fi._FlagVisitor._call_name(body[0].value.func))
                if inner:
                    delegated[fn.name] = inner

        def uses_of(assign: ast.AST, var: str, _tree=tree, _parents=parents) -> list[ast.AST]:
            scope: ast.AST = _tree
            cur = _parents.get(id(assign))
            while cur is not None:
                if isinstance(cur, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    scope = cur
                    break
                cur = _parents.get(id(cur))
            return [n for n in ast.walk(scope) if isinstance(n, ast.Name) and n.id == var and isinstance(n.ctx, ast.Load)]

        class Classifier(fi._FlagVisitor):
            def on_read(self, flag: str, node: ast.Call, call_name: str) -> None:
                kind = _helper_kind(call_name) or delegated.get(call_name)
                found = {kind} if kind else _consumption(node, parents, uses_of)
                if found:
                    kinds.setdefault(flag, set()).update(found)

        Classifier(delegators, fi._flag_constants(tree)).visit(tree)
    return kinds


def flag_kind(kinds: set[str] | None) -> str:
    """One label per flag. ``number`` wins over ``bool``: a flag any reader parses as a number is never claimed to be a switch."""
    kinds = kinds or set()
    if "number" in kinds:
        return "number"
    if "bool" in kinds:
        return "bool"
    if "str" in kinds:
        return "str"
    return "unknown"


def build(inventory: dict, kinds: dict[str, set[str]] | None = None) -> dict:
    """``kinds`` = ``reader_kinds(...)``; without it no flag is known to be a bool, so no numeric default is turned into on/off."""
    prod = inventory.get("flags", {}).get("prod", {})
    flags = {}
    for name in sorted(prod):
        rec = prod[name]
        kind = flag_kind((kinds or {}).get(name))
        tokens = sorted({normalise_default(d, kind) for d in rec.get("defaults", ["-"])})
        flags[name] = {"defaults": tokens, "kind": kind, "readers": len(rec.get("readers", []))}
    return {"kind": "code-defaults", "source": INVENTORY, "note": NOTE, "prod_flag_count": len(flags), "flags": flags}


def compatible(claim: str, defaults: list[str]) -> bool:
    """A roadmap claim ``[default ZOE_X=<claim>]`` holds when it names one of the flag's default tokens (``off`` also holds for
    ``unset``: an empty default is how most mode flags ship off)."""
    claim = claim.strip().lower()
    return claim in defaults or (claim == "off" and "unset" in defaults)


def render(state: dict) -> str:
    return json.dumps(state, indent=1, sort_keys=True) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--repo", type=Path, default=REPO)
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed file differs from the derivation")
    args = ap.parse_args(argv)
    inv = json.loads((args.repo / INVENTORY).read_text())
    text = render(build(inv, reader_kinds(args.repo, inv)))
    out = args.repo / OUT
    if args.check:
        if not out.exists() or out.read_text() != text:
            print(f"{OUT} is stale: run python3 tools/audit/live_state.py", file=sys.stderr)
            return 1
        return 0
    out.write_text(text)
    print(f"wrote {OUT} ({len(json.loads(text)['flags'])} flags)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
