#!/usr/bin/env python3
"""Generate docs/knowledge/live-state.json - the ZOE_* flag DEFAULTS as the code ships them.

This file is NOT the live state of the box, despite its name (the name is the roadmap's, deep-dive task C1). It is derived
from ``docs/knowledge/flag-inventory.json`` (itself extracted from the code by ``flag_inventory.py``), so it can only say what
a flag does when nobody sets it. What is actually ON in the running processes is read with
``scripts/maintenance/zoe_ground_truth.sh``; a roadmap that wants to say "this flag is ON live" says so in prose and marks the
date, and the CI check (``tests/unit/test_roadmap_flag_claims.py``) never pretends to verify it.

What it is for: ``docs/ROADMAP.md`` writes a claim about a code default as ``[default ZOE_NAME=value]``, and the test fails when
that claim contradicts this derivation. That is the check that would have caught "documented dark, actually shadow/enforce"
drift of the kind recorded in the 2026-10-18 deep dive, for the half of it code can see (the default).

Deterministic by construction (sorted, no timestamps), so regeneration diffs show real flag changes only.

Usage:
    python3 tools/audit/live_state.py            # write docs/knowledge/live-state.json
    python3 tools/audit/live_state.py --check    # exit 1 when the committed file is stale (writes nothing)
"""
from __future__ import annotations

import argparse
import ast
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
INVENTORY = "docs/knowledge/flag-inventory.json"
OUT = "docs/knowledge/live-state.json"

_ON = {"1", "true", "yes", "on", "enabled", "enable"}
_OFF = {"0", "false", "no", "off", "none", "disabled", "disable", "null"}

NOTE = (
    "GENERATED by tools/audit/live_state.py from docs/knowledge/flag-inventory.json. These are the flag DEFAULTS as the code "
    "ships them, not the values set on the running box (read those with scripts/maintenance/zoe_ground_truth.sh). "
    "'unset' = no default argument or an empty-string default; it is compatible with a claim of 'off'."
)


def normalise_default(raw: str) -> str:
    """One inventory default expression -> a comparable token: on | off | unset | dynamic | required | <lowercased literal>."""
    text = str(raw).strip()
    if text in ("-", ""):
        return "unset"
    if text == "dynamic":
        return "dynamic"
    if text == "(required)":
        return "required"
    try:
        value = ast.literal_eval(text)
    except (ValueError, SyntaxError):
        return text.lower()
    if value is None:
        return "unset"
    if isinstance(value, bool):
        return "on" if value else "off"
    token = str(value).strip().lower()
    if token == "":
        return "unset"
    if token in _ON:
        return "on"
    if token in _OFF:
        return "off"
    return token


def build(inventory: dict) -> dict:
    prod = inventory.get("flags", {}).get("prod", {})
    flags = {}
    for name in sorted(prod):
        rec = prod[name]
        tokens = sorted({normalise_default(d) for d in rec.get("defaults", ["-"])})
        flags[name] = {"defaults": tokens, "readers": len(rec.get("readers", []))}
    return {"kind": "code-defaults", "source": INVENTORY, "note": NOTE, "prod_flag_count": len(flags), "flags": flags}


def compatible(claim: str, defaults: list[str]) -> bool:
    """A roadmap claim ``[default ZOE_X=<claim>]`` holds when it names one of the flag's default tokens (``off`` also holds for
    ``unset``: an empty default is how most mode flags ship off)."""
    claim = claim.strip().lower()
    return claim in defaults or (claim == "off" and "unset" in defaults)


def render(state: dict) -> str:
    return json.dumps(state, indent=1, sort_keys=True) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--repo", type=Path, default=REPO)
    ap.add_argument("--check", action="store_true", help="exit 1 if the committed file differs from the derivation")
    args = ap.parse_args(argv)
    inv = json.loads((args.repo / INVENTORY).read_text())
    text = render(build(inv))
    out = args.repo / OUT
    if args.check:
        if not out.exists() or out.read_text() != text:
            print(f"{OUT} is stale: run python3 tools/audit/live_state.py", file=sys.stderr)
            return 1
        return 0
    out.write_text(text)
    print(f"wrote {OUT} ({len(json.loads(text)['flags'])} flags)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
