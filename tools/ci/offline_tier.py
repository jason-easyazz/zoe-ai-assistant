#!/usr/bin/env python3
"""The OFFLINE test tier: the fast, hermetic subset of the ``ci_safe`` lanes a Zoe box runs with no network.

    python3 tools/ci/offline_tier.py                 # print the selection, then verify it offline
    python3 tools/ci/offline_tier.py list            # print the selection only
    python3 tools/ci/offline_tier.py verify --json - # machine-readable result on stdout
    python3 tools/ci/offline_tier.py measure         # run EVERY ci_safe file alone, offline (slow; the evidence)
    python3 tools/ci/offline_tier.py select          # rebuild tools/ci/offline_tier.json from a measurement

The tier is the manifest ``tools/ci/offline_tier.json`` (generated by ``select``, committed so a box needs no
measurement to use it). ``verify`` runs each lane's selected files in one pytest process with
``tools/ci/offline_guard.py`` in ``block`` mode, inside an empty network namespace when the kernel allows one,
with a throwaway ``HOME``, and fails when a test fails, when anything reached for a non-loopback address,
started a program outside the base set or wrote under ``HOME``, when a selected file is missing or runs nothing, or (``--enforce-budget``) when the run exceeds the manifest's time or memory budget.

No network, no GitHub, no ``gh``: only the interpreter that runs it, pytest and the repo. Docs:
``docs/knowledge/offline-test-tier.md``.
"""
from __future__ import annotations

import argparse
import ast
import concurrent.futures
import fcntl
import json
import os
import platform
import socket
import struct
import subprocess
import sys
import tempfile
import time
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
MANIFEST = REPO / "tools" / "ci" / "offline_tier.json"
MEASUREMENT = Path.home() / ".cache" / "zoe" / "offline-tier" / "measurement.json"     # never in the repo
ZD = "services/zoe-data"
# The two marker lanes of validate.yml, with its env. No POSTGRES_URL and no CI: the tier is database-free.
LANES = {
    "zoe-data": {"root": f"{ZD}/tests", "pythonpath": [ZD, "tools/ci"],
                 "args": [f"--ignore={ZD}/tests/samantha_live"]},
    "unit": {"root": "tests/unit", "pythonpath": [".", ZD, "tools/ci"], "args": []},
}
PYTEST = ["-m", "ci_safe", "-q", "-p", "no:cacheprovider", "-p", "offline_guard", "--override-ini=asyncio_mode=auto"]
# Programs a tier test may start: python, git and the POSIX tools every Zoe box has. Repo scripts (``repo:...``)
# and a test's own temp-dir fakes (``stub``) are fine. Anything else (node, npm, gh, openssl, jq, ...) keeps a
# file out of the tier.
BASE_BINARIES = {"git", "bash", "sh", "dash", "env", "true", "false", "sleep", "cat", "date", "uname", "echo", "sed",
                 "awk", "tail", "head", "which", "flock", "pgrep", "kill", "ldconfig", "lscpu", "stub"}


def external(spawned) -> list[str]:
    """The started programs that are NOT part of the base set."""
    return sorted(b for b in spawned if b not in BASE_BINARIES and not b.startswith(("python", "repo:")))


DROP_ENV = ("CI", "POSTGRES_URL", "DATABASE_URL", "GITHUB_ACTIONS", "PYTEST_ADDOPTS", "GIT_CONFIG_GLOBAL")


def lane_env(lane: str, report: Path, mode: str) -> dict:
    env = {k: v for k, v in os.environ.items() if k not in DROP_ENV and not k.lower().endswith("_proxy")}
    env.update(PYTHONPATH=os.pathsep.join(str(REPO / p) for p in LANES[lane]["pythonpath"]),
               ZOE_DATA_DB=":memory:", ZOE_MEMORY_STARTUP_STRICT="false", PYTHONDONTWRITEBYTECODE="1",
               OFFLINE_GUARD=mode, OFFLINE_GUARD_REPORT=str(report), TZ=os.environ.get("TZ", "UTC"))
    return env


# --- empty network namespace (loopback only) ------------------------------------------------------------

def _enter_netns() -> None:
    """Move THIS process into a new user + network namespace and bring ``lo`` up. Raises OSError if refused."""
    uid, gid = os.getuid(), os.getgid()
    os.unshare(os.CLONE_NEWUSER | os.CLONE_NEWNET)
    Path("/proc/self/setgroups").write_text("deny")
    Path("/proc/self/uid_map").write_text(f"{uid} {uid} 1")
    Path("/proc/self/gid_map").write_text(f"{gid} {gid} 1")
    with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as s:
        ifr = struct.pack("16sH14s", b"lo", 0, b"")
        flags = struct.unpack("16sH14s", fcntl.ioctl(s, 0x8913, ifr))[1]            # SIOCGIFFLAGS
        fcntl.ioctl(s, 0x8914, struct.pack("16sH14s", b"lo", flags | 0x1, b""))     # SIOCSIFFLAGS, IFF_UP


def netns_prefix() -> list[str]:
    """argv prefix that runs a command in an empty network namespace, or [] when the kernel refuses one."""
    if not hasattr(os, "unshare"):
        return []
    me = [sys.executable, str(Path(__file__).resolve()), "_netns"]
    try:
        ok = subprocess.run([*me, sys.executable, "-c", "pass"], capture_output=True, timeout=30).returncode == 0
    except (OSError, subprocess.SubprocessError):
        ok = False
    return me if ok else []


# --- running pytest -------------------------------------------------------------------------------------

def run_pytest(lane: str, targets: list[str], mode: str, prefix: list[str], timeout: float) -> dict:
    """One guarded pytest process over ``targets``; returns the guard's report plus rc / wall / output tail."""
    with tempfile.TemporaryDirectory(prefix="zoe-offline-") as tmp:
        report, home = Path(tmp) / "report.json", Path(tmp) / "home"
        home.mkdir()
        cmd = [*prefix, sys.executable, "-m", "pytest", *targets, *LANES[lane]["args"], *PYTEST]
        env = {**lane_env(lane, report, mode), "HOME": str(home)}      # a throwaway HOME: no live ~/.zoe, read or written
        started = time.monotonic()
        try:
            p = subprocess.run(cmd, cwd=REPO, env=env, capture_output=True, text=True,
                               timeout=timeout, stdin=subprocess.DEVNULL)
            rc, tail = p.returncode, (p.stdout + p.stderr)[-1500:]
        except subprocess.TimeoutExpired:
            rc, tail = 124, f"timeout after {timeout:.0f}s"
        out = {"rc": rc, "process_wall_s": round(time.monotonic() - started, 2), "tail": tail}
        if report.exists():
            out.update(json.loads(report.read_text(encoding="utf-8")))
        out["home_writes"] = sorted(str(p.relative_to(home)) for p in home.rglob("*") if not p.is_dir())[:20]
        return out


def ci_safe_files(lane: str) -> list[str]:
    """Test files of a lane that carry the marker (a text scan; pytest then deselects per test)."""
    root = REPO / LANES[lane]["root"]
    skip = root / "samantha_live"
    return sorted(str(p.relative_to(REPO)) for p in root.rglob("test_*.py")
                  if skip not in p.parents and "ci_safe" in p.read_text(encoding="utf-8", errors="replace"))


# --- measure --------------------------------------------------------------------------------------------

def cmd_measure(a) -> int:
    prefix = [] if a.no_netns else netns_prefix()
    jobs = [(lane, f) for lane in LANES for f in ci_safe_files(lane) if not a.only or a.only in f]
    print(f"measuring {len(jobs)} ci_safe files, one process each, {a.jobs} at a time; "
          f"netns={'on' if prefix else 'UNAVAILABLE (guard only)'}", file=sys.stderr)
    files: dict[str, dict] = {}

    def one(job):
        lane, f = job
        r = run_pytest(lane, [f], "block", prefix, a.timeout)
        r["lane"] = lane
        if r["rc"] == 0:
            r.pop("tail")
        return f, r

    with concurrent.futures.ThreadPoolExecutor(a.jobs) as pool:
        for i, (f, r) in enumerate(pool.map(one, jobs), 1):
            files[f] = r
            if i % 50 == 0:
                print(f"  {i}/{len(jobs)}", file=sys.stderr)
    out = {"schema": 1, "host": host_info(), "netns": bool(prefix), "jobs": a.jobs, "files": files}
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(json.dumps(out, indent=1) + "\n", encoding="utf-8")
    bad = sum(1 for r in files.values() if r["rc"] != 0 or r.get("violations"))
    print(f"wrote {a.out}: {len(files)} files, {bad} not hermetic or not green offline", file=sys.stderr)
    return 0


def host_info() -> dict:
    return {"machine": platform.machine(), "python": platform.python_version(), "cpus": os.cpu_count(),
            "commit": subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=REPO, capture_output=True,
                                     text=True).stdout.strip()}


# --- select ---------------------------------------------------------------------------------------------

def zoe_data_modules() -> dict[str, bool]:
    """Every zoe-data source module -> whether it has a function or class body (else import is all there is)."""
    out = {}
    root = REPO / ZD
    for p in sorted(root.rglob("*.py")):
        rel = p.relative_to(root)
        if rel.parts[0] in ("tests", "alembic") or "__pycache__" in rel.parts:
            continue
        tree = ast.parse(p.read_text(encoding="utf-8", errors="replace"))
        out[str(rel)] = any(isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef, ast.Lambda))
                            for n in ast.walk(tree))
    return out


def why_excluded(r: dict) -> str | None:
    """Why a measured file cannot be in the tier, or None when it is hermetic and green offline."""
    if r.get("violations"):
        v = r["violations"][0]
        return f"network: {v['kind']} {v['target']}"
    if r["rc"] != 0:
        return f"not green offline (rc={r['rc']})"
    if r.get("home_writes"):
        return "writes under HOME: ~/" + r["home_writes"][0]
    extra = external(r.get("spawned", {}))
    if extra:
        return "external binary: " + ", ".join(extra)
    if not r.get("counts", {}).get("passed"):
        return "nothing passed (all skipped)"
    return None


def cmd_select(a) -> int:
    m = json.loads(a.measurement.read_text(encoding="utf-8"))
    modules = zoe_data_modules()
    ok = {f: r for f, r in m["files"].items() if why_excluded(r) is None}
    startup = min(r["wall_s"] for r in ok.values())
    cost = {f: max(r["wall_s"] - startup, 0.0) + 0.05 for f, r in ok.items()}
    def reach(r):       # modules a file EXECUTES (a function or class body ran); import counts only where that is all there is
        return {mod for mod in set(r.get("executed", [])) | {x for x in r.get("imported", []) if not modules.get(x, True)}
                if mod in modules}

    covers = {f: reach(r) for f, r in ok.items()}
    # Greedy weighted set cover (most new modules per second), then drop any pick that became redundant.
    need, chosen = set().union(*covers.values()), []
    while need:
        best = max(ok, key=lambda f: (len(covers[f] & need) / cost[f], f))
        chosen.append(best)
        need -= covers[best]
    for f in sorted(chosen, key=lambda f: -cost[f]):
        rest = set().union(*(covers[g] for g in chosen if g != f))
        if covers[f] <= rest:
            chosen.remove(f)
    owner: dict[str, str] = {}
    for f in sorted(chosen, key=lambda f: cost[f]):
        for mod in covers[f]:
            owner.setdefault(mod, f)
    covered = set(owner)
    lanes = {lane: {} for lane in LANES}
    for f in sorted(chosen):
        r = ok[f]
        lanes[r["lane"]][f] = {"s": round(cost[f], 2), "rss_mb": round(r["peak_rss_mb"]), "tests": r["counts"]["passed"],
                               "covers": sorted(mod for mod, g in owner.items() if g == f)}
    # Why each uncovered module is uncovered: the ci_safe file that does execute it and what keeps that file out, or nothing at all.
    uncovered = {}
    for mod in sorted(set(modules) - covered):
        by = sorted(f for f, r in m["files"].items() if f not in ok and mod in reach(r))
        uncovered[mod] = f"only {by[0]} ({why_excluded(m['files'][by[0]])})" if by else "no ci_safe test executes it"
    total = sum(cost[f] for f in chosen) + startup * len(LANES)
    manifest = {
        "schema": 1,
        "note": "GENERATED by tools/ci/offline_tier.py select - do not edit. See docs/knowledge/offline-test-tier.md.",
        "measured_on": m["host"],
        "budget_s": a.budget_s or int(total * a.budget_factor + 0.5),
        "budget_rss_mb": a.budget_rss_mb or int(max(ok[f]["peak_rss_mb"] for f in chosen) * 2),
        "measured_s": round(total, 1),
        "modules": {"total": len(modules), "covered": len(covered)},
        "uncovered": uncovered,
        "lanes": lanes,
    }
    write_manifest(manifest, a.manifest)
    print(f"tier: {len(chosen)} of {len(m['files'])} ci_safe files ({len(ok)} hermetic), ~{total:.0f}s measured, "
          f"{len(covered)}/{len(modules)} zoe-data modules; wrote {a.manifest}", file=sys.stderr)
    return 0


def write_manifest(manifest: dict, path: Path) -> None:
    """Stable, diff-friendly JSON: one line per test file."""
    head = {k: v for k, v in manifest.items() if k not in ("lanes", "measured_on", "modules")}
    lines = [json.dumps(head, indent=1)[:-2] + ","]
    lines += [f" {json.dumps(k)}: {json.dumps(manifest[k])}," for k in ("measured_on", "modules")]
    lines.append(' "lanes": {')
    for i, (lane, files) in enumerate(manifest["lanes"].items()):
        lines.append(f'  {json.dumps(lane)}: {{')
        lines += [f"   {json.dumps(f)}: {json.dumps(v)}{',' if j < len(files) - 1 else ''}"
                  for j, (f, v) in enumerate(files.items())]
        lines.append("  }" + ("," if i < len(manifest["lanes"]) - 1 else ""))
    path.write_text("\n".join(lines) + "\n }\n}\n", encoding="utf-8")


# --- list / verify --------------------------------------------------------------------------------------

def load_manifest(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def cmd_list(a) -> int:
    man = load_manifest(a.manifest)
    for lane, files in man["lanes"].items():
        print(f"# lane {lane}: {len(files)} files")
        for f, v in files.items():
            print(f"{f}  {v['s']}s  {v['rss_mb']}MB  {v['tests']} tests  covers {len(v['covers'])}")
    mods = man["modules"]
    print(f"# budget {man['budget_s']}s / {man['budget_rss_mb']}MB; measured {man['measured_s']}s on "
          f"{man['measured_on']['machine']}; covers {mods['covered']}/{mods['total']} zoe-data modules")
    return 0


def cmd_verify(a) -> int:
    man = load_manifest(a.manifest)
    prefix = [] if a.no_netns else netns_prefix()
    result = {"schema": 1, "netns": bool(prefix), "budget_s": man["budget_s"], "budget_rss_mb": man["budget_rss_mb"],
              "lanes": {}, "problems": []}
    problems = result["problems"]
    for lane, files in man["lanes"].items():
        missing = [f for f in files if not (REPO / f).is_file()]
        problems += [f"{f}: selected file is missing" for f in missing]
        targets = [f for f in files if f not in missing]
        if not targets:
            continue
        r = run_pytest(lane, targets, "block", prefix, a.timeout)
        ran = r.get("files", {})
        problems += [f"{f}: selected file ran no test" for f in targets if f not in ran]
        problems += [f"{v['test']}: {v['kind']} {v['target']} (non-loopback)" for v in r.get("violations", [])]
        problems += [f"lane {lane}: started external binary {b} ({', '.join(r['spawned'][b][:3])})"
                     for b in external(r.get("spawned", {}))]
        problems += [f"lane {lane}: a test wrote under HOME: ~/{w}" for w in r["home_writes"]]
        if r["rc"] != 0:
            problems.append(f"lane {lane}: pytest rc={r['rc']}: {r['tail'][-600:]}")
        result["lanes"][lane] = {"rc": r["rc"], "files": len(targets), "counts": r.get("counts", {}),
                                 "wall_s": r["process_wall_s"], "peak_rss_mb": r.get("peak_rss_mb"),
                                 "children_peak_rss_mb": r.get("children_peak_rss_mb"),
                                 "slowest": sorted(((v["seconds"], f) for f, v in ran.items()), reverse=True)[:5]}
    result["wall_s"] = round(sum(v["wall_s"] for v in result["lanes"].values()), 1)
    result["peak_rss_mb"] = max((v["peak_rss_mb"] or 0 for v in result["lanes"].values()), default=0)
    over = []
    if result["wall_s"] > man["budget_s"]:
        over.append(f"wall {result['wall_s']}s is over the {man['budget_s']}s budget")
    if result["peak_rss_mb"] > man["budget_rss_mb"]:
        over.append(f"peak RSS {result['peak_rss_mb']}MB is over the {man['budget_rss_mb']}MB budget")
    result["over_budget"] = over
    if a.enforce_budget:
        problems += over
    result["rc"] = 1 if problems else 0
    out = sys.stderr if a.json else sys.stdout
    for lane, v in result["lanes"].items():
        print(f"lane {lane}: {v['files']} files, {v['counts']}, {v['wall_s']}s, peak RSS {v['peak_rss_mb']}MB", file=out)
    print(f"offline tier: {result['wall_s']}s of {man['budget_s']}s, peak RSS {result['peak_rss_mb']}MB of "
          f"{man['budget_rss_mb']}MB, netns={'on' if prefix else 'off (in-process guard only)'}", file=out)
    for line in over if not a.enforce_budget else []:
        print(f"note: {line}", file=out)
    for line in problems:
        print(f"FAIL: {line}", file=out)
    print("offline tier: " + ("FAILED" if problems else "hermetic and green"), file=out)
    if a.json:
        text = json.dumps(result, indent=1) + "\n"
        sys.stdout.write(text) if a.json == "-" else Path(a.json).write_text(text, encoding="utf-8")
    return result["rc"]


def main(argv: list[str] | None = None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    if argv[:1] == ["_netns"]:                      # internal: exec the rest of argv inside an empty netns
        _enter_netns()
        os.execvp(argv[1], argv[1:])
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("command", nargs="?", default="run", choices=["run", "list", "verify", "measure", "select"])
    ap.add_argument("--manifest", type=Path, default=MANIFEST)
    ap.add_argument("--measurement", type=Path, default=MEASUREMENT)
    ap.add_argument("--out", type=Path, default=MEASUREMENT, help="measure: where to write the measurement")
    ap.add_argument("--json", default="", help="verify: write the result as JSON to this path ('-' = stdout)")
    ap.add_argument("--no-netns", action="store_true", help="in-process guard only (no network namespace)")
    ap.add_argument("--enforce-budget", action="store_true", help="verify: over budget is a failure")
    ap.add_argument("--timeout", type=float, default=1800, help="seconds per pytest process")
    ap.add_argument("--jobs", type=int, default=1, help="measure: processes at a time (1 = honest timings)")
    ap.add_argument("--only", default="", help="measure: only files whose path contains this")
    ap.add_argument("--budget-s", type=int, default=0, help="select: stated time budget (default measured x factor)")
    ap.add_argument("--budget-factor", type=float, default=3.0)
    ap.add_argument("--budget-rss-mb", type=int, default=0)
    a = ap.parse_args(argv)
    if a.command == "run":
        return cmd_list(a) or cmd_verify(a)
    return {"list": cmd_list, "verify": cmd_verify, "measure": cmd_measure, "select": cmd_select}[a.command](a)


if __name__ == "__main__":
    raise SystemExit(main())
